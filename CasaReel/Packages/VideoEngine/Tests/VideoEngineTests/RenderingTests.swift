/// Test photos (solid colors or a gradient) written as JPEG, plus helpers to read pixels back.
final class RenderFixtures {
    let directory = FileManager.default.temporaryDirectory.appending(path: "VideoEngineTests-\(UUID().uuidString)", directoryHint: .isDirectory)
    var outputs: URL { directory.appending(path: "renders", directoryHint: .isDirectory) }

    init() throws {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    }

    deinit {
        try? FileManager.default.removeItem(at: directory)
    }

    func photo(red: CGFloat, green: CGFloat, blue: CGFloat, width: Int = 1600, height: Int = 1200) throws -> PreparedPhoto {
        guard let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                      space: CGColorSpace(name: CGColorSpace.sRGB) ?? CGColorSpaceCreateDeviceRGB(),
                                      bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue) else { throw CocoaError(.fileWriteUnknown) }
        context.setFillColor(red: red, green: green, blue: blue, alpha: 1)
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        context.setFillColor(red: 1 - red, green: 1 - green, blue: 1 - blue, alpha: 1)
        context.fill(CGRect(x: width / 2, y: height / 2, width: width / 10, height: height / 10))
        guard let image = context.makeImage() else { throw CocoaError(.fileWriteUnknown) }
        let url = directory.appending(path: "\(UUID().uuidString).jpg")
        guard let destination = CGImageDestinationCreateWithURL(url as CFURL, UTType.jpeg.identifier as CFString, 1, nil) else { throw CocoaError(.fileWriteUnknown) }
        CGImageDestinationAddImage(destination, image, [kCGImageDestinationLossyCompressionQuality: 0.95] as CFDictionary)
        guard CGImageDestinationFinalize(destination) else { throw CocoaError(.fileWriteUnknown) }
        return PreparedPhoto(fileURL: url, sha256: "", size: 0, width: width, height: height, mimeType: .jpeg, perceptualHash: 0)
    }

    /// Writes `seconds` of a 440 Hz tone as AAC.
    func tone(seconds: Double) throws -> URL {
        let url = directory.appending(path: "tone.m4a")
        let format = try #require(AVAudioFormat(standardFormatWithSampleRate: 44_100, channels: 2))
        let file = try AVAudioFile(forWriting: url, settings: [AVFormatIDKey: kAudioFormatMPEG4AAC, AVSampleRateKey: 44_100, AVNumberOfChannelsKey: 2])
        let frames = AVAudioFrameCount(seconds * 44_100)
        let buffer = try #require(AVAudioPCMBuffer(pcmFormat: format, frameCapacity: frames))
        buffer.frameLength = frames
        for channel in 0..<2 {
            let samples = try #require(buffer.floatChannelData?[channel])
            for index in 0..<Int(frames) { samples[index] = sinf(Float(index) * 2 * .pi * 440 / 44_100) * 0.3 }
        }
        try file.write(from: buffer)
        return url
    }

    static func pixel(of image: CIImage, at point: CGPoint, context: CIContext) -> (Double, Double, Double) {
        var bytes = [UInt8](repeating: 0, count: 4)
        context.render(image, toBitmap: &bytes, rowBytes: 4, bounds: CGRect(origin: point, size: CGSize(width: 1, height: 1)),
                       format: .RGBA8, colorSpace: CGColorSpace(name: CGColorSpace.sRGB))
        return (Double(bytes[0]) / 255, Double(bytes[1]) / 255, Double(bytes[2]) / 255)
    }
}

/// "Golden" key frames: instead of stored reference images (generated by the same code), each frame
/// is checked against colors that follow from the template, with a tolerance.
struct KeyFrameTests {
    private let context = CIContext()

    private func renderer(kind: String, watermark: Bool = false, fixtures: RenderFixtures) throws -> FrameRenderer {
        let transition = #"{"type":"\#(kind)","duration_ms":1000}"#
        let motion = #"{"type":"static","from":[0,0,1],"to":[0,0,1],"easing":"linear"}"#
        let spec = try TemplateSpec.decode(Data(templateJSON(scenes: [scene(duration: 3000, motion: motion, transition: transition)]).utf8))
        let red = try fixtures.photo(red: 1, green: 0, blue: 0), blue = try fixtures.photo(red: 0, green: 0, blue: 1)
        let photos = [red, blue].map { (size: CGSize(width: $0.width, height: $0.height), focus: CGRect(x: 0, y: 0, width: 1, height: 1), faces: [CGRect](), caption: String?.none) }
        let timeline = SceneTimeline.build(spec: spec, aspect: .horizontal, photos: photos, targetDurationMs: nil)
        return FrameRenderer(timeline: timeline, photoURLs: [red.fileURL, blue.fileURL], outputSize: CGSize(width: 1920, height: 1080),
                             context: context, title: nil, watermark: watermark, watermarkPosition: .bottomRight)
    }

    private func close(_ a: (Double, Double, Double), _ b: (Double, Double, Double), tolerance: Double = 0.08) -> Bool {
        abs(a.0 - b.0) < tolerance && abs(a.1 - b.1) < tolerance && abs(a.2 - b.2) < tolerance
    }

    private let probe = CGPoint(x: 200, y: 900)

    @Test func crossfadeMidpointIsAnEvenMix() throws {
        let fixtures = try RenderFixtures()
        let renderer = try renderer(kind: "crossfade", fixtures: fixtures)
        #expect(close(RenderFixtures.pixel(of: try renderer.image(atMs: 500), at: probe, context: context), (1, 0, 0)))
        // Transition runs from 2000 to 3000 ms; 2500 is its midpoint. Core Image blends in linear light,
        // so an even mix of pure red and blue is 0.5 linear ≈ 0.735 in sRGB on each channel.
        let mid = RenderFixtures.pixel(of: try renderer.image(atMs: 2500), at: probe, context: context)
        #expect(close(mid, (0.735, 0, 0.735)), "\(mid)")
        #expect(close(RenderFixtures.pixel(of: try renderer.image(atMs: 4000), at: probe, context: context), (0, 0, 1)))
    }

    @Test func dipToBlackPassesThroughBlack() throws {
        let fixtures = try RenderFixtures()
        let renderer = try renderer(kind: "dip_to_black", fixtures: fixtures)
        #expect(close(RenderFixtures.pixel(of: try renderer.image(atMs: 2500), at: probe, context: context), (0, 0, 0)))
    }

    @Test func slideMovesTheIncomingPhotoInFromTheRight() throws {
        let fixtures = try RenderFixtures()
        let renderer = try renderer(kind: "slide", fixtures: fixtures)
        let frame = try renderer.image(atMs: 2500)
        #expect(close(RenderFixtures.pixel(of: frame, at: CGPoint(x: 200, y: 900), context: context), (1, 0, 0)))
        #expect(close(RenderFixtures.pixel(of: frame, at: CGPoint(x: 1700, y: 900), context: context), (0, 0, 1)))
    }

    @Test func watermarkOnlyAppearsWhenRequired() throws {
        let fixtures = try RenderFixtures()
        // Inside the watermark label: it starts 4% (77 px) from the bottom-right corner.
        let corner = CGPoint(x: 1920 - 77 - 20, y: 77 + 20)
        let plain = RenderFixtures.pixel(of: try renderer(kind: "crossfade", fixtures: fixtures).image(atMs: 500), at: corner, context: context)
        let marked = RenderFixtures.pixel(of: try renderer(kind: "crossfade", watermark: true, fixtures: fixtures).image(atMs: 500), at: corner, context: context)
        #expect(close(plain, (1, 0, 0)))
        #expect(!close(marked, (1, 0, 0)), "\(marked)")
    }

    @Test func overlaysFadeAndTreatTextAsPlainText() {
        #expect(FrameRenderer.fade(0, total: 3000) == 0)
        #expect(FrameRenderer.fade(1500, total: 3000) == 1)
        #expect(FrameRenderer.fade(3000, total: 3000) == 0)
        #expect(OverlayFactory.caption("   ", outputWidth: 1080) == nil)
        let markup = OverlayFactory.caption("<b>Sala</b> %@ \\(x) \u{202E}", outputWidth: 1080)
        #expect(markup != nil)
        let long = OverlayFactory.caption(String(repeating: "W", count: 500), outputWidth: 1080)
        let short = OverlayFactory.caption(String(repeating: "W", count: OverlayFactory.maxCaptionLength), outputWidth: 1080)
        #expect(long?.extent == short?.extent, "captions are truncated")
    }
}

/// Simulated device temperature.
final class FakeThermal: ThermalMonitoring {
    private let current: OSAllocatedUnfairLock<ProcessInfo.ThermalState>
    init(_ state: ProcessInfo.ThermalState) { current = OSAllocatedUnfairLock(initialState: state) }
    var state: ProcessInfo.ThermalState { current.withLock { $0 } }
    func set(_ state: ProcessInfo.ThermalState) { current.withLock { $0 = state } }
}

/// Renders run one at a time: in parallel they compete for the Simulator's CPU and blow the time limits.
@Suite(.serialized)
struct RenderIntegrationTests {
    private func renderer(_ fixtures: RenderFixtures, thermal: any ThermalMonitoring = FakeThermal(.nominal), keepAwake: @escaping @Sendable (Bool) async -> Void = { _ in }) throws -> VideoEngineRenderer {
        var options = VideoWriter.Options()
        options.heatPollInterval = .milliseconds(20)
        options.maxHeatPause = .milliseconds(200)
        return VideoEngineRenderer(library: try TemplateLibrary(), thermal: thermal, outputDirectory: fixtures.outputs, keepAwake: keepAwake, writerOptions: options)
    }

    private func slug(_ raw: String) throws -> TemplateSlug { try #require(TemplateSlug(rawValue: raw)) }

    private func collect(_ stream: AsyncThrowingStream<RenderEvent, any Error>) async throws -> (RenderedVideo?, [RenderEvent]) {
        var events: [RenderEvent] = []
        for try await event in stream {
            events.append(event)
            if case .finished(let video) = event { return (video, events) }
        }
        return (nil, events)
    }

    @Test(.timeLimit(.minutes(10)))
    func rendersTenSecondHorizontalVideo() async throws {
        let fixtures = try RenderFixtures()
        let photos = try [(1.0, 0.2, 0.2), (0.2, 1.0, 0.2), (0.2, 0.2, 1.0)].map { try fixtures.photo(red: $0.0, green: $0.1, blue: $0.2) }
        let request = VideoRenderRequest(
            photos: photos, templateSlug: try slug("classic-clean"), aspect: .horizontal,
            captions: [photos[0].id: "Sala"], title: "Casa de praia", watermark: true, targetDurationMs: 11_400
        )
        let awake = OSAllocatedUnfairLock(initialState: [Bool]())

        let (video, events) = try await collect(try renderer(fixtures, keepAwake: { on in awake.withLock { $0.append(on) } }).render(request))

        let rendered = try #require(video)
        let asset = AVURLAsset(url: rendered.fileURL)
        let duration = try await asset.load(.duration).seconds
        let track = try #require(try await asset.loadTracks(withMediaType: .video).first)
        let size = try await track.load(.naturalSize)
        let fps = try await track.load(.nominalFrameRate)

        #expect(abs(duration - 10) < 0.2, "duration \(duration)")
        #expect(size == CGSize(width: 1920, height: 1080))
        #expect(abs(fps - 30) < 1)
        #expect(try await asset.loadTracks(withMediaType: .audio).isEmpty)
        #expect(rendered.durationMs == 10_000)
        #expect(rendered.sha256 == (try FileDigest.sha256(of: rendered.fileURL)))
        #expect(rendered.sizeBytes > 0)
        #expect(rendered.watermark)
        let thumbnail = try #require(CGImageSourceCreateWithURL(rendered.thumbnailURL as CFURL, nil))
        let properties = try #require(CGImageSourceCopyPropertiesAtIndex(thumbnail, 0, nil) as? [CFString: Any])
        #expect(properties[kCGImagePropertyPixelWidth] as? Int == 1280)
        #expect(properties[kCGImagePropertyPixelHeight] as? Int == 720)
        #expect(events.contains(.progress(0)) && events.contains(.progress(1)))
        try await Task.sleep(for: .milliseconds(50))
        #expect(awake.withLock { $0 } == [true, false])

        let files = try FileManager.default.contentsOfDirectory(atPath: fixtures.outputs.path).sorted()
        #expect(files.count == 2, "only the final video and its thumbnail remain: \(files)")
    }

    @Test(.timeLimit(.minutes(5)))
    func rendersVerticalVideoWithMusic() async throws {
        let fixtures = try RenderFixtures()
        let photos = try (0..<3).map { _ in try fixtures.photo(red: 0.8, green: 0.6, blue: 0.3) }
        let request = VideoRenderRequest(
            photos: photos, templateSlug: try slug("dynamic-social"), aspect: .vertical,
            watermark: false, audioTrackURL: try fixtures.tone(seconds: 2)
        )

        let (video, _) = try await collect(try renderer(fixtures).render(request))

        let rendered = try #require(video)
        let asset = AVURLAsset(url: rendered.fileURL)
        let videoTrack = try #require(try await asset.loadTracks(withMediaType: .video).first)
        #expect(try await videoTrack.load(.naturalSize) == CGSize(width: 1080, height: 1920))
        let audioTrack = try #require(try await asset.loadTracks(withMediaType: .audio).first, "music track muxed in")
        let audioDuration = try await audioTrack.load(.timeRange).duration.seconds
        #expect(abs(audioDuration - Double(rendered.durationMs) / 1000) < 0.3, "the 2 s tone loops to the video length")
        let thumbnail = try #require(CGImageSourceCreateWithURL(rendered.thumbnailURL as CFURL, nil))
        let properties = try #require(CGImageSourceCopyPropertiesAtIndex(thumbnail, 0, nil) as? [CFString: Any])
        #expect(properties[kCGImagePropertyPixelWidth] as? Int == 720)
    }

    @Test func rejectsUnknownTemplateAndUnsupportedAspect() async throws {
        let fixtures = try RenderFixtures()
        let photo = try fixtures.photo(red: 1, green: 1, blue: 1)
        let renderer = try renderer(fixtures)
        await #expect(throws: RenderError.unsupportedAspect) {
            _ = try await collect(renderer.render(VideoRenderRequest(photos: [photo], templateSlug: try slug("dynamic-social"), aspect: .horizontal, watermark: false)))
        }
        await #expect(throws: RenderError.unknownTemplate) {
            _ = try await collect(renderer.render(VideoRenderRequest(photos: [photo], templateSlug: try slug("missing"), aspect: .vertical, watermark: false)))
        }
        await #expect(throws: RenderError.notEnoughPhotos) {
            _ = try await collect(renderer.render(VideoRenderRequest(photos: [], templateSlug: try slug("classic-clean"), aspect: .vertical, watermark: false)))
        }
    }

    @Test(.timeLimit(.minutes(3)))
    func cancellingRemovesPartialFiles() async throws {
        let fixtures = try RenderFixtures()
        let photos = try (0..<6).map { _ in try fixtures.photo(red: 0.3, green: 0.5, blue: 0.7) }
        let renderer = try renderer(fixtures)
        let request = VideoRenderRequest(photos: photos, templateSlug: try slug("cinematic-soft"), aspect: .vertical, watermark: false)

        // A cancelled consumer simply stops receiving events; what matters is that the render stops and cleans up.
        let task = Task {
            for try await event in renderer.render(request) {
                if case .progress(let value) = event, value > 0 { withUnsafeCurrentTask { $0?.cancel() } }
            }
        }
        _ = try? await task.value

        var leftovers: [String] = ["pending"]
        for _ in 0..<50 where !leftovers.isEmpty {
            try await Task.sleep(for: .milliseconds(100))
            leftovers = (try? FileManager.default.contentsOfDirectory(atPath: fixtures.outputs.path)) ?? []
        }
        #expect(leftovers.isEmpty, "\(leftovers)")
    }

    @Test(.timeLimit(.minutes(2)))
    func criticalHeatAbortsAndCleansUp() async throws {
        let fixtures = try RenderFixtures()
        let photo = try fixtures.photo(red: 1, green: 0.5, blue: 0)
        let request = VideoRenderRequest(photos: [photo, photo], templateSlug: try slug("classic-clean"), aspect: .vertical, watermark: false)

        await #expect(throws: RenderError.overheated) { _ = try await collect(try renderer(fixtures, thermal: FakeThermal(.critical)).render(request)) }

        let serious = FakeThermal(.serious)
        var events: [RenderEvent] = []
        await #expect(throws: RenderError.overheated) {
            for try await event in try renderer(fixtures, thermal: serious).render(request) { events.append(event) }
        }
        #expect(events.contains(.pausedForHeat))
        #expect(((try? FileManager.default.contentsOfDirectory(atPath: fixtures.outputs.path)) ?? []).isEmpty)
    }

    @Test func discardDeletesOnlyRendererFiles() async throws {
        let fixtures = try RenderFixtures()
        let renderer = try renderer(fixtures)
        let outside = fixtures.directory.appending(path: "keep.mp4")
        try Data("x".utf8).write(to: outside)
        let slug = try slug("classic-clean")
        renderer.discard(RenderedVideo(fileURL: outside, thumbnailURL: outside, templateSlug: slug, templateVersion: 1,
                                       aspect: .vertical, durationMs: 0, sizeBytes: 0, sha256: "", watermark: false))
        #expect(FileManager.default.fileExists(atPath: outside.path))
        #expect(renderer.templates.map(\.slug.rawValue) == ["classic-clean", "cinematic-soft", "dynamic-social"])
    }
}

@Suite(.serialized)
struct SceneRequestTests {
    @Test func perSceneDurationsAndDuplicatesShapeTheTimeline() throws {
        let fixtures = try RenderFixtures()
        let photo = try fixtures.photo(red: 0.5, green: 0.5, blue: 0.5)
        let renderer = VideoEngineRenderer(library: try TemplateLibrary(), outputDirectory: fixtures.outputs)
        let slug = try #require(TemplateSlug(rawValue: "classic-clean"))
        let request = VideoRenderRequest(
            scenes: [VideoScene(photo: photo, caption: "Sala", durationMs: 2_000), VideoScene(photo: photo, caption: "Sala de novo", durationMs: 20_000)],
            templateSlug: slug, aspect: .vertical, watermark: false
        )

        let (_, timeline) = try renderer.timeline(for: request)

        #expect(timeline.entries.map(\.durationMs) == [2_000, 8_000], "overrides are clamped to 1–8 s")
        #expect(timeline.entries.map(\.caption) == ["Sala", "Sala de novo"])
        #expect(VideoAspect.vertical.renderSize(for: .preview) == (540, 960))
    }

    @Test(.timeLimit(.minutes(3)))
    func previewRendersAtHalfSizeWithClosingText() async throws {
        let fixtures = try RenderFixtures()
        let photo = try fixtures.photo(red: 0.2, green: 0.4, blue: 0.8)
        let renderer = VideoEngineRenderer(library: try TemplateLibrary(), outputDirectory: fixtures.outputs)
        let slug = try #require(TemplateSlug(rawValue: "cinematic-soft"))
        let request = VideoRenderRequest(
            scenes: [VideoScene(photo: photo, durationMs: 2_000), VideoScene(photo: photo, durationMs: 2_000)],
            templateSlug: slug, aspect: .horizontal, closingText: "Reserve pelo link", watermark: true, quality: .preview
        )

        var video: RenderedVideo?
        for try await event in renderer.render(request) {
            if case .finished(let rendered) = event { video = rendered }
        }

        let rendered = try #require(video)
        let track = try #require(try await AVURLAsset(url: rendered.fileURL).loadTracks(withMediaType: .video).first)
        #expect(try await track.load(.naturalSize) == CGSize(width: 960, height: 540))
        #expect(rendered.templateSlug == slug)
    }
}
